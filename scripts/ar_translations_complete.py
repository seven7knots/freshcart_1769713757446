def main():
    # Load current Arabic ARB
    ar_path = os.path.join(L10N_DIR, 'app_ar.arb')
    with open(ar_path, 'r', encoding='utf-8') as f:
        ar_arb = json.load(f)

    # Update with complete translations
    updated = 0
    for key, ar_value in COMPLETE_AR.items():
        if key in ar_arb:
            ar_arb[key] = ar_value
            updated += 1

    # Write back
    with open(ar_path, 'w', encoding='utf-8') as f:
        json.dump(ar_arb, f, indent=2, ensure_ascii=False)

    # Count remaining English-only values
    en_path = os.path.join(L10N_DIR, 'app_en.arb')
    with open(en_path, 'r', encoding='utf-8') as f:
        en_arb = json.load(f)

    still_english = 0
    for key in en_arb:
        if key.startswith('@@'):
            continue
        if key in ar_arb and ar_arb[key] == en_arb[key]:
            still_english += 1

    print(f"Updated {updated} Arabic translations")
    print(f"Remaining untranslated (English fallback): {still_english}")

if __name__ == '__main__':
    main()
